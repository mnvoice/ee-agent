import logging
from typing import Any

logging.basicConfig(level=logging.INFO, format="%(levelname)s: %(message)s")
logger = logging.getLogger(__name__)

DATA_DIR = os.path.join(os.path.dirname(__file__), "..", "data")

SUBJECT_MAP: dict[int, str] = {
    1: "전기자기학",
    2: "전력공학",
    3: "전기기기",
    4: "회로이론및제어공학",
    5: "전기설비기술기준",
}

# Keywords that indicate a calculation-type question
CALC_KEYWORDS = [
    "몇", "구하", "계산", "값은", "크기는", "세기는", "전압은", "전류는",
    "전력은", "용량은", "저항은", "속도는", "토크는", "효율은", "거리는",
    "높이는", "굵기는", "단면적", "실효값", "최대값", "범위는", "얼마",
    "kW", "kVA", "kVar", "var", "Ω", "V", "A", "Hz", "m/s", "rpm",
    "Wb", "H", "F", "N", "dB",
]


def get_subject(q_no: int) -> str:
    """Return subject name based on question number range."""
    group = (q_no - 1) // 20 + 1
    return SUBJECT_MAP[group]


def determine_q_type(text: str, solution_hint: str) -> str:
    """Determine question type based on keywords in text and hint."""
    combined = text + " " + solution_hint
    for kw in CALC_KEYWORDS:
        if kw in combined:
            return "계산형"
    return "개념형"


def build_question(
    year: int,
    session: str,
    q_tuple: tuple[int, str, list[str], list[str], int, str, str],
) -> dict[str, Any]:
    """Convert a question tuple to the standard JSON dict."""
    q_no, text, choices, answer, solution_hint, tag = (
        q_tuple[0],
        q_tuple[1],
        q_tuple[2],
        q_tuple[3],
        q_tuple[4],
        q_tuple[5],
    )

    # Flatten nested lists in choices (safety for question 15 in session3)
    flat_choices: list[str] = []
    for c in choices:
        if isinstance(c, list):
            flat_choices.append(str(c[0]) if c else "")
        else:
            flat_choices.append(str(c))

    return {
        "year": year,
        "session": session,
        "subject": get_subject(q_no),
        "q_no": q_no,
        "text": text,
        "choices": flat_choices,
        "answer": answer,
        "solution": solution_hint,
        "difficulty": 3,
        "q_type": determine_q_type(text, solution_hint),
        "tag": tag,
        "steps": {},
        "quality": "complete",
    }


def save_session(
    year: int,
    session_label: str,
    raw_data: list[tuple],
) -> int:
    """Save one session's data to JSON file. Returns question count."""
    questions = [build_question(year, session_label, q) for q in raw_data]
    filename = f"questions_기출_{year}_{session_label}.json"
    filepath = os.path.join(DATA_DIR, filename)
    with open(filepath, "w", encoding="utf-8") as f:
        json.dump(questions, f, ensure_ascii=False, indent=2)
    logger.info("Saved %d questions to %s", len(questions), filename)
    return len(questions)


